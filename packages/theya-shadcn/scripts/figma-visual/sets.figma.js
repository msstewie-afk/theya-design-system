// Figma side of scripts/figma-visual-diff.mjs: lists every component set
// (and standalone component) on the Theya file's design-system pages as
// `Name<TAB>nodeId`. The diff script reads the variants of each from the
// Figma REST API itself, so this only needs rerunning when sets are added,
// removed or renamed.
// Paste into the Figma MCP use_figma tool (or the plugin console) on the
// Theya file and save the returned `txt` as scripts/figma-visual/sets.txt.
const out = [];
for (const p of figma.root.children) {
  if (/icon|cover|archive|playground|---/i.test(p.name)) continue;
  await p.loadAsync();
  for (const s of p.findAll((n) => n.type === 'COMPONENT_SET' || (n.type === 'COMPONENT' && n.parent.type !== 'COMPONENT_SET'))) {
    if (/^[._]|^state$/.test(s.name)) continue;
    out.push(s.name + '\t' + s.id);
  }
}
const txt = '# Generated by scripts/figma-visual/sets.figma.js — Figma component set<TAB>node id\n' + out.join('\n') + '\n';
return { sets: out.length, txt };
