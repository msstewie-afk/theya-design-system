#!/usr/bin/env node
/**
 * Visual diff: each Figma variant against the same component rendered in
 * Storybook, pixel by pixel.
 *
 * Inputs
 * - scripts/figma-visual/sets.txt — the Figma component sets, `Name<TAB>nodeId`.
 *   Their variants are read from the Figma REST API on every run; only
 *   resting states are compared (no hover / focus / pressed / open), at most
 *   --max per set (default 10), picked so every prop value shows up once.
 *   Regenerate the list with scripts/figma-visual/sets.figma.js (paste into
 *   the Figma MCP use_figma tool or the plugin console) when sets are added,
 *   removed or renamed.
 * - spec/components/*.json — which code component a Figma set is, its props
 *   and its Storybook stories (generated by build-spec.mjs).
 * - scripts/figma-visual/overrides.json — optional per-set tuning:
 *   { "<Figma set name>": {
 *       "component": "<code export, when the names differ>",
 *       "story": "<story id>", "args": {…}, "selector": "<css>",
 *       "values": { "<figma prop>=<value>": { <code args> } },
 *       "text": false,          // keep the story's own sample text
 *       "skip": "<reason>" } }
 *
 * How a pair is made
 * - Figma set "Button/primary" → code component Button with tone="primary";
 *   "Checkbox" → Checkbox. The story is the component's Playground (else
 *   Default, else its first story).
 * - Variant props that are also props of the code component become story
 *   args (true/false → booleans, numbers → numbers). The rest (state, and
 *   Figma-only props) are listed in the report as not passed.
 * - The variant's first text ("Badge", "Save") replaces the story's sample
 *   text (its string `children`, else `label` / `title` / `value` arg), so
 *   copy differences don't drown out real ones.
 * - The story is loaded once per set; each variant only updates its args
 *   (Storybook's updateStoryArgs), then the first element in #storybook-root
 *   (or `selector`) is captured at 2×. Figma renders the variant at 2× via
 *   the REST images endpoint.
 * - pixelmatch compares the two (both padded to the larger size). Text that
 *   differs between the Figma sample and the story shows up too: read the
 *   report side by side, the percentage is a sorting aid, not a verdict.
 *
 * Output: build/figma-visual/ (git-ignored) — index.html, results.json and
 * per variant figma.png / code.png / diff.png.
 *
 * Usage (Storybook running on :6008):
 *   FIGMA_TOKEN=<personal access token> node scripts/figma-visual-diff.mjs [--only Select,TextField] [--file <figma file key>] [--url http://localhost:6008] [--theme dark]
 * The token needs read access to the file (Figma → Settings → Security →
 * Personal access tokens, scope "File content: read"). It is only sent to
 * api.figma.com.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > -1 ? process.argv[i + 1] : fallback;
};
const FILE_KEY = arg('file', 'LPj5ZGhCmC2OEwXJPF7isw');
const URL_BASE = arg('url', 'http://localhost:6008').replace(/\/$/, '');
// --only: comma-separated, matched exactly against Figma set names (case-insensitive).
const ONLY = (arg('only', '') || '').toLowerCase().split(',').map((x) => x.trim()).filter(Boolean);
const THEME = arg('theme', 'light');
const SCALE = 2;
const OUT = path.join(ROOT, 'build/figma-visual');
const TOKEN = process.env.FIGMA_TOKEN;
if (!TOKEN) {
  console.error('FIGMA_TOKEN is not set. Create a personal access token in Figma (Settings → Security) and run:\n  FIGMA_TOKEN=… node scripts/figma-visual-diff.mjs');
  process.exit(1);
}

// Same Playwright as @storybook/test-runner; pixelmatch and pngjs come with
// jest-image-snapshot (the visual-regression run), so no new dependencies.
const runnerDir = path.dirname(require.resolve('@storybook/test-runner'));
const { chromium } = require(require.resolve('playwright', { paths: [runnerDir] }));
const snapshotDir = path.dirname(require.resolve('jest-image-snapshot'));
const pixelmatchMod = require(require.resolve('pixelmatch', { paths: [snapshotDir] }));
const pixelmatch = pixelmatchMod.default ?? pixelmatchMod;
const { PNG } = require(require.resolve('pngjs', { paths: [snapshotDir] }));

// --- Figma side ------------------------------------------------------------------

const setList = fs
  .readFileSync(path.join(ROOT, 'scripts/figma-visual/sets.txt'), 'utf8')
  .split('\n')
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((line) => {
    const [name, id] = line.split('\t');
    return { name, id };
  })
  .filter((s) => !ONLY.length || ONLY.includes(s.name.toLowerCase()));

// Resting states only: Storybook shows a story at rest, so hover / focus /
// pressed / open variants have nothing to be compared with.
const REST = new Set(['default', 'idle', 'closed', 'empty', 'first', 'ask', 'false']);
const MAX_VARIANTS = Number(arg('max', 10));
const parseProps = (name) => Object.fromEntries(name.split(',').map((kv) => kv.trim().split('=')).filter((kv) => kv.length === 2));

// Figma answers slowly for big nodes and rate-limits bursts (429 with
// Retry-After): every call has a timeout and is retried a few times.
async function figmaGet(url, attempt = 1) {
  let res;
  try {
    res = await fetch(url, { headers: { 'X-Figma-Token': TOKEN }, signal: AbortSignal.timeout(90_000) });
  } catch (e) {
    if (attempt >= 4) throw new Error(`Figma request failed: ${e.message}`);
    console.log(`  Figma timed out, retry ${attempt}…`);
    return figmaGet(url, attempt + 1);
  }
  if (res.status === 429 && attempt < 6) {
    const wait = Math.min(Number(res.headers.get('retry-after')) || 20, 120);
    console.log(`  Figma rate limit, waiting ${wait}s…`);
    await new Promise((r) => setTimeout(r, wait * 1000));
    return figmaGet(url, attempt + 1);
  }
  if (!res.ok) throw new Error(`Figma ${res.status}: ${await res.text()}`);
  const json = await res.json();
  if (json.err) throw new Error(`Figma: ${json.err}`);
  return json;
}

/** Each set's variants from the REST API, filtered to resting states and capped
 * at MAX_VARIANTS so that every prop value still shows up at least once. */
async function loadVariants(list) {
  const out = [];
  for (let i = 0; i < list.length; i += 50) {
    const batch = list.slice(i, i + 50);
    const json = await figmaGet(`https://api.figma.com/v1/files/${FILE_KEY}/nodes?ids=${encodeURIComponent(batch.map((s) => s.id).join(','))}&depth=1`);
    for (const s of batch) {
      const doc = json.nodes?.[s.id]?.document;
      if (!doc) {
        out.push({ ...s, variants: [], missing: true });
        continue;
      }
      let variants =
        doc.type === 'COMPONENT_SET'
          ? (doc.children ?? []).filter((c) => c.type === 'COMPONENT').map((c) => ({ id: c.id, props: parseProps(c.name) }))
          : [{ id: doc.id, props: {} }];
      variants = variants.filter((v) => ['state', 'open', 'busy'].every((k) => !(k in v.props) || REST.has(v.props[k])));
      if (variants.length > MAX_VARIANTS) {
        const seen = new Set();
        const keep = [];
        for (const v of variants) {
          const keys = Object.entries(v.props).map(([k, x]) => `${k}=${x}`);
          if (keys.some((k) => !seen.has(k))) {
            keep.push(v);
            keys.forEach((k) => seen.add(k));
          }
          if (keep.length >= MAX_VARIANTS) break;
        }
        variants = keep;
      }
      out.push({ ...s, variants });
    }
  }
  // The first visible text of each variant ("Badge", "Save", "5"), so the
  // story can show the same words — otherwise every text-bearing component
  // differs by its sample copy alone.
  const all = out.flatMap((s) => s.variants);
  const firstText = (n) => {
    if (n.visible === false) return null;
    if (n.type === 'TEXT' && n.characters?.trim()) return n.characters;
    for (const c of n.children ?? []) {
      const t = firstText(c);
      if (t) return t;
    }
    return null;
  };
  for (let i = 0; i < all.length; i += 25) {
    const batch = all.slice(i, i + 25);
    const json = await figmaGet(`https://api.figma.com/v1/files/${FILE_KEY}/nodes?ids=${encodeURIComponent(batch.map((v) => v.id).join(','))}`);
    for (const v of batch) v.text = firstText(json.nodes?.[v.id]?.document ?? {});
    console.log(`  Figma texts ${Math.min(i + 25, all.length)}/${all.length}`);
  }
  return out;
}

const overridesPath = path.join(ROOT, 'scripts/figma-visual/overrides.json');
const overrides = fs.existsSync(overridesPath) ? JSON.parse(fs.readFileSync(overridesPath, 'utf8')) : {};

// --- code side -------------------------------------------------------------------

const specDir = path.join(ROOT, 'spec/components');
/** Exported component name → { spec, component } */
const byExport = new Map();
for (const f of fs.readdirSync(specDir)) {
  const spec = JSON.parse(fs.readFileSync(path.join(specDir, f), 'utf8'));
  for (const component of spec.components ?? []) if (!byExport.has(component.name)) byExport.set(component.name, { spec, component });
}

function pickStory(spec) {
  const stories = spec.storybook?.stories ?? [];
  return (stories.find((s) => s.name === 'Playground') ?? stories.find((s) => s.name === 'Default') ?? stories[0])?.id;
}

function toArg(prop, value) {
  if (value === 'true' || value === 'false') return value === 'true';
  if (/^-?\d+(\.\d+)?$/.test(value) && /\bnumber\b/.test(prop.type ?? '')) return Number(value);
  return value;
}

/** Figma set → { story, args per variant, passed / dropped props } or { skip } */
function resolve(set) {
  const o = overrides[set.name] ?? {};
  if (o.skip) return { skip: o.skip };
  const [base, fixedTone] = set.name.split('/');
  const hit = byExport.get(o.component ?? base);
  if (!hit && !o.story) return { skip: `no code component named ${base}` };
  // Props of every part in the spec, not just the root: a story's args often
  // feed a sub-part (Select's error / widthSize live on SelectTrigger).
  const props = new Map();
  for (const c of hit?.spec.components ?? []) for (const p of c.props ?? []) if (!props.has(p.name)) props.set(p.name, p);
  for (const p of hit?.component.props ?? []) props.set(p.name, p);
  const story = o.story ?? pickStory(hit.spec);
  if (!story) return { skip: `${base} has no stories` };
  const dropped = new Set();
  const variants = set.variants.map((v) => {
    const args = { ...(o.args ?? {}) };
    if (fixedTone && props.has('tone')) args.tone = fixedTone;
    for (const [k, val] of Object.entries(v.props)) {
      // overrides.values: a Figma prop value that maps to other code props,
      // e.g. { "content=dot": { "dot": true } }.
      const mapped = o.values?.[`${k}=${val}`];
      if (mapped) Object.assign(args, mapped);
      else if (props.has(k)) args[k] = toArg(props.get(k), val);
      else dropped.add(k);
    }
    return { ...v, args };
  });
  return { story, selector: o.selector, width: o.width, bleed: o.bleed === true, useText: o.text !== false, variants, dropped: [...dropped] };
}

// --- Figma images ----------------------------------------------------------------

// Figma renders are cached in build/figma-visual-cache/ (by node id), so a
// rerun while tuning overrides only asks Figma for nodes it hasn't rendered.
// --refresh-figma renders everything again (after editing the Figma file).
const CACHE = path.join(ROOT, 'build/figma-visual-cache');
const REFRESH = process.argv.includes('--refresh-figma');
const cachePath = (id) => path.join(CACHE, `${id.replace(/[^0-9a-z]+/gi, '-')}.png`);
let figmaUrls = {};
async function figmaPng(id) {
  const p = cachePath(id);
  if (fs.existsSync(p)) return fs.readFileSync(p);
  const url = figmaUrls[id];
  if (!url) throw new Error('Figma returned no image for this node');
  const buf = Buffer.from(await (await fetch(url, { signal: AbortSignal.timeout(60_000) })).arrayBuffer());
  fs.mkdirSync(CACHE, { recursive: true });
  fs.writeFileSync(p, buf);
  return buf;
}

// use_absolute_bounds: render exactly the node's box. Without it Figma grows
// the image by the drop-shadow bleed (Card: +2px per side), while the code
// capture is clipped to the element box — every pixel shifted, ~8% noise.
async function figmaImages(ids) {
  const urls = {};
  for (let i = 0; i < ids.length; i += 15) {
    const batch = ids.slice(i, i + 15);
    const json = await figmaGet(`https://api.figma.com/v1/images/${FILE_KEY}?ids=${encodeURIComponent(batch.join(','))}&format=png&scale=${SCALE}&use_absolute_bounds=true`);
    Object.assign(urls, json.images);
    console.log(`  Figma images ${Math.min(i + 15, ids.length)}/${ids.length}`);
  }
  return urls;
}

// --- compare ---------------------------------------------------------------------

function pad(png, w, h) {
  if (png.width === w && png.height === h) return png;
  const out = new PNG({ width: w, height: h });
  out.data.fill(255); // white, opaque
  PNG.bitblt(png, out, 0, 0, png.width, png.height, 0, 0);
  return out;
}

function compare(figmaBuf, codeBuf, diffPath) {
  const a = PNG.sync.read(figmaBuf);
  const b = PNG.sync.read(codeBuf);
  const w = Math.max(a.width, b.width);
  const h = Math.max(a.height, b.height);
  const A = pad(a, w, h);
  const B = pad(b, w, h);
  const diff = new PNG({ width: w, height: h });
  const changed = pixelmatch(A.data, B.data, diff.data, w, h, { threshold: 0.1, includeAA: false });
  fs.writeFileSync(diffPath, PNG.sync.write(diff));
  return {
    ratio: changed / (w * h),
    figmaSize: [a.width / SCALE, a.height / SCALE],
    codeSize: [b.width / SCALE, b.height / SCALE],
  };
}

// --- run -------------------------------------------------------------------------

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

// Fail fast (before the slow Figma part) when Storybook isn't up yet.
try {
  const res = await fetch(`${URL_BASE}/index.json`, { signal: AbortSignal.timeout(15_000) });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  await res.json();
} catch (e) {
  console.error(`Storybook is not answering at ${URL_BASE} (${e.message}). Start it (pnpm storybook), wait until it prints its URL, then rerun.`);
  process.exit(1);
}

const sets = await loadVariants(setList);
const plan = sets.map((s) => ({ set: s, r: s.missing ? { skip: `node ${s.id} not found in the Figma file — rerun sets.figma.js` } : resolve(s) }));
const allIds = plan.flatMap((p) => (p.r.skip ? [] : p.r.variants.map((v) => v.id)));
if (REFRESH) fs.rmSync(CACHE, { recursive: true, force: true });
const toRender = allIds.filter((id) => !fs.existsSync(cachePath(id)));
console.log(`${plan.length} Figma sets, ${allIds.length} variants (${toRender.length} not cached, rendering them in Figma)…`);
figmaUrls = toRender.length ? await figmaImages(toRender) : {};

const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1200, height: 900 }, deviceScaleFactor: SCALE, reducedMotion: 'reduce' });
const page = await context.newPage();
const results = [];
const slug = (s) => s.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '').toLowerCase();

for (const { set, r } of plan) {
  if (r.skip) {
    results.push({ set: set.name, skip: r.skip });
    continue;
  }
  const globals = THEME === 'dark' ? '&globals=theme:dark' : '';
  // Load the story and let its play function finish (a play that opens and
  // closes a popover leaves the trigger focused and tinted otherwise). While
  // another agent edits story files Storybook's index can fail for a few
  // seconds (error display, empty root): retry the load a few times.
  let rendered = false;
  for (let attempt = 1; attempt <= 4 && !rendered; attempt++) {
    await page.goto(`${URL_BASE}/iframe.html?id=${r.story}&viewMode=story${globals}`, { waitUntil: 'load' });
    try {
      await page.waitForSelector('#storybook-root > *', { timeout: 15000 });
      await page
        .waitForFunction(() => ['finished', 'completed', 'played', 'errored', 'aborted'].includes(window.__STORYBOOK_PREVIEW__?.currentRender?.phase), null, { timeout: 15000 })
        .catch(() => {});
      rendered = !(await page.evaluate(() => document.body.classList.contains('sb-show-errordisplay')));
    } catch {
      rendered = false;
    }
    if (!rendered) await page.waitForTimeout(3000 * attempt);
  }
  if (!rendered) {
    results.push({ set: set.name, skip: `story ${r.story} did not render` });
    continue;
  }
  // Colour and size transitions (0.15–0.22s) would be caught mid-way after
  // an args update; reduced motion alone doesn't turn all of them off.
  await page.addStyleTag({ content: '*,*::before,*::after{transition:none!important;animation:none!important;caret-color:transparent!important}' });
  for (const v of r.variants) {
    const dir = path.join(OUT, slug(set.name), slug(Object.values(v.props).join('-') || 'default'));
    fs.mkdirSync(dir, { recursive: true });
    const row = { set: set.name, variant: v.props, node: v.id, story: r.story, args: v.args, dropped: r.dropped, dir: path.relative(OUT, dir) };
    try {
      // Reset to the story's own args first (the previous variant's must not
      // leak into this one), then apply this variant's — one render each.
      await page.evaluate(
        async ({ storyId, args, text }) => {
          const channel = window.__STORYBOOK_ADDONS_CHANNEL__;
          // Put the Figma sample text into whichever string arg the story
          // shows as its text (children, else label / title / value).
          const initial = window.__STORYBOOK_PREVIEW__?.currentRender?.story?.initialArgs ?? {};
          if (text) {
            const key = ['children', 'label', 'title', 'value'].find((k) => typeof initial[k] === 'string' && !(k in args));
            if (key) args = { ...args, [key]: text };
          }
          const emitAndWait = (event, payload) =>
            new Promise((done) => {
              const t = setTimeout(done, 3000);
              channel.once('storyRendered', () => (clearTimeout(t), done()));
              channel.emit(event, payload);
            });
          await emitAndWait('resetStoryArgs', { storyId });
          if (Object.keys(args).length) await emitAndWait('updateStoryArgs', { storyId, updatedArgs: args });
        },
        { storyId: r.story, args: v.args, text: r.useText === false ? null : v.text },
      );
      const figmaBuf = await figmaPng(v.id);
      fs.writeFileSync(path.join(dir, 'figma.png'), figmaBuf);
      // Give the story the Figma frame's width: a full-width component
      // (a field, a bar, a chart) then lays out exactly as wide as in Figma
      // instead of filling the 1200px page. Hugging components don't care.
      const figmaWidth = PNG.sync.read(figmaBuf).width / SCALE;
      await page.evaluate((w) => {
        const root = document.querySelector('#storybook-root');
        // content-box: the root's own padding (Storybook's `padded` layout)
        // must not eat into the width the component gets.
        if (root) {
          root.style.boxSizing = 'content-box';
          root.style.width = w ? `${w}px` : '';
        }
      }, r.width === false ? 0 : figmaWidth);
      // Play functions leave focus and hover behind (a focused swatch, a
      // hovered trigger); the Figma variants are at rest.
      await page.mouse.move(0, 0);
      await page.evaluate(() => document.activeElement instanceof HTMLElement && document.activeElement.blur());
      await page.evaluate(() => document.fonts.ready);
      await page.waitForTimeout(150);
      // The capture target: `selector`, else the story's first element —
      // stepping through display:contents wrappers (Radix providers, a
      // Sidebar layout), which have no box of their own to screenshot.
      const found = await page.evaluate((sel) => {
        document.querySelectorAll('[data-fv-target]').forEach((n) => n.removeAttribute('data-fv-target'));
        let el;
        if (sel === '@field') {
          // A form control without its label / hint: the bordered box around
          // the first input-like element, widened to a same-size wrapper that
          // also holds its absolutely placed buttons (clear, steppers).
          const root = document.querySelector('#storybook-root');
          // Candidates in priority order (not document order: a chip's remove
          // button or a visually hidden input can come first); the first one
          // that is visible and sits in a bordered box wins.
          const bordered = (n) => {
            while (n && n !== root && !(parseFloat(getComputedStyle(n).borderTopWidth) > 0)) n = n.parentElement;
            return n === root ? null : n;
          };
          el = null;
          for (const q of ['textarea', 'input:not([type=hidden])', '[role=combobox]', 'button[aria-haspopup]', 'button']) {
            for (const c of root.querySelectorAll(q)) {
              const b = c.getBoundingClientRect();
              if (!b.width || !b.height) continue;
              const box = bordered(c);
              if (box && box.getBoundingClientRect().height >= 24) {
                el = box;
                break;
              }
            }
            if (el) break;
          }
          const same = (a, b) => Math.abs(a.width - b.width) < 1 && Math.abs(a.height - b.height) < 1;
          while (el && el.parentElement && el.parentElement !== root && same(el.getBoundingClientRect(), el.parentElement.getBoundingClientRect())) el = el.parentElement;
        } else {
          el = sel ? document.querySelector(sel) : document.querySelector('#storybook-root > *');
        }
        while (el && getComputedStyle(el).display === 'contents') el = el.firstElementChild;
        if (!el) return false;
        el.setAttribute('data-fv-target', '');
        return true;
      }, r.selector ?? null);
      const el = found && (await page.$('[data-fv-target]'));
      if (!el) throw new Error(`nothing matches ${r.selector ?? '#storybook-root > *'}`);
      // Clip to the element's exact box instead of el.screenshot(): a
      // centered story sits on half pixels (x = 584.5), which the element
      // screenshot rounds outwards into a 1px-larger image. At 2× a half
      // CSS pixel is a whole device pixel, so the clip stays exact.
      // overrides.bleed: grow the box to the children that overflow it — a
      // Slider's 16px thumb hangs off its 6px track, and Figma's frame holds both.
      const box = await el.evaluate((n, bleed) => {
        const b = n.getBoundingClientRect();
        let [x0, y0, x1, y1] = [b.left, b.top, b.right, b.bottom];
        if (bleed) {
          for (const c of n.querySelectorAll('*')) {
            const cb = c.getBoundingClientRect();
            if (cb.width <= 1 || cb.height <= 1) continue; // sr-only inputs
            x0 = Math.min(x0, cb.left); y0 = Math.min(y0, cb.top);
            x1 = Math.max(x1, cb.right); y1 = Math.max(y1, cb.bottom);
          }
        }
        return { x: x0 + window.scrollX, y: y0 + window.scrollY, width: x1 - x0, height: y1 - y0 };
      }, r.bleed);
      if (!box.width || !box.height) throw new Error('the element has no size');
      const codeBuf = await page.screenshot({ clip: box, animations: 'disabled', fullPage: true });
      fs.writeFileSync(path.join(dir, 'code.png'), codeBuf);
      Object.assign(row, compare(figmaBuf, codeBuf, path.join(dir, 'diff.png')));
    } catch (e) {
      row.error = String(e.message ?? e);
    }
    results.push(row);
    const pct = row.ratio != null ? `${(row.ratio * 100).toFixed(1)}%` : row.error;
    console.log(`${set.name} ${JSON.stringify(v.props)} → ${pct}`);
  }
}
await browser.close();

fs.writeFileSync(path.join(OUT, 'results.json'), JSON.stringify(results, null, 2));

// --- report ----------------------------------------------------------------------

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]);
const rows = results
  .filter((r) => !r.skip)
  .sort((a, b) => (b.ratio ?? 2) - (a.ratio ?? 2))
  .map((r) => {
    const size = r.figmaSize ? `${r.figmaSize.join('×')} / ${r.codeSize.join('×')}` : '';
    const sizeBad = r.figmaSize && (r.figmaSize[0] !== r.codeSize[0] || r.figmaSize[1] !== r.codeSize[1]);
    const img = (f) => `<a href="${r.dir}/${f}"><img src="${r.dir}/${f}" loading="lazy"></a>`;
    return `<tr><td><b>${esc(r.set)}</b><br><small>${esc(Object.entries(r.variant).map(([k, v]) => `${k}=${v}`).join(', '))}</small><br><small>${esc(r.story)}</small>${r.dropped?.length ? `<br><small class="muted">not passed: ${esc(r.dropped.join(', '))}</small>` : ''}</td>
<td class="num">${r.ratio != null ? (r.ratio * 100).toFixed(1) + '%' : `<span class="err">${esc(r.error)}</span>`}</td><td class="num${sizeBad ? ' err' : ''}">${size}</td>
<td>${r.error ? '' : img('figma.png')}</td><td>${r.error ? '' : img('code.png')}</td><td>${r.error ? '' : img('diff.png')}</td></tr>`;
  })
  .join('\n');
const skipped = results.filter((r) => r.skip).map((r) => `<li><b>${esc(r.set)}</b> — ${esc(r.skip)}</li>`).join('');
fs.writeFileSync(
  path.join(OUT, 'index.html'),
  `<!doctype html><meta charset="utf-8"><title>Figma ↔ Storybook visual diff</title>
<style>body{font:14px/1.4 system-ui;margin:24px;color:#151529}table{border-collapse:collapse;width:100%}td,th{border-bottom:1px solid #ddd;padding:8px;vertical-align:top;text-align:left}
img{max-width:320px;max-height:240px;background:repeating-conic-gradient(#eee 0 25%,#fff 0 50%) 0/16px 16px}.num{white-space:nowrap}.err{color:#b40d49}.muted{color:#5f6190}</style>
<h1>Figma ↔ Storybook</h1><p>${new Date().toISOString().slice(0, 16).replace('T', ' ')} · file ${FILE_KEY} · ${THEME} · sorted by changed pixels. Size is Figma / code in px.</p>
<table><tr><th>Variant</th><th>Diff</th><th>Size</th><th>Figma</th><th>Code</th><th>Diff</th></tr>${rows}</table>
<h2>Skipped</h2><ul>${skipped}</ul>`,
);
