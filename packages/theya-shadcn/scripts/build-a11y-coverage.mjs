#!/usr/bin/env node
/**
 * WCAG 2.2 A/AA coverage table: for every criterion, which tool checks it,
 * whether the tools alone can verify it (automated), only some of it (partly)
 * or not at all (manual), and where the library stands. Read from
 * spec/a11y.json (scripts/build-a11y.mjs), so it can't drift from the matrix.
 *
 * Writes docs/a11y-coverage.md and docs/a11y-coverage.ru.md at the repo root.
 *
 *   node scripts/build-a11y-coverage.mjs           write
 *   node scripts/build-a11y-coverage.mjs --check   fail if stale
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(ROOT, '../..');
const CHECK = process.argv.includes('--check');
const matrix = JSON.parse(fs.readFileSync(path.join(ROOT, 'spec/a11y.json'), 'utf8'));

// Evidence kinds (a11y/criteria.json) → the tool behind each, and whether it runs without a person.
const TOOL = {
  axe: { en: 'axe-core (test-runner, light + dark)', ru: 'axe-core (test-runner, светлая и тёмная)', auto: true },
  keyboard: { en: 'keyboard play tests, a11y-auto Tab pass, a11y-states', ru: 'play-тесты с клавиатурой, Tab-проход a11y-auto, a11y-states', auto: true },
  auto: { en: 'a11y-auto', ru: 'a11y-auto', auto: true },
  tree: { en: 'a11y-tree', ru: 'a11y-tree', auto: true },
  hover: { en: 'a11y-states (hover and focus content)', ru: 'a11y-states (всплывающее по наведению и фокусу)', auto: true },
  input: { en: 'a11y-states (typing, toggling)', ru: 'a11y-states (ввод, переключение)', auto: true },
  reflow360: { en: 'the suite at 360px', ru: 'прогон при 360 px', auto: true },
  code: { en: 'a11y-code (source scan)', ru: 'a11y-code (скан исходников)', auto: true },
  reducedMotion: { en: 'source read (motion-safe guards)', ru: 'чтение кода (защита motion-safe)', auto: true },
  screenReader: { en: 'screen-reader pass (VoiceOver)', ru: 'проход скринридером (VoiceOver)', auto: false },
  review: { en: 'manual review', ru: 'ручная проверка', auto: false },
};
const T = {
  en: {
    title: 'Accessibility coverage: WCAG 2.2 A/AA',
    intro: (n, date) =>
      `Generated by \`scripts/build-a11y-coverage.mjs\` from \`spec/a11y.json\` (the accessibility matrix). Do not edit. Russian: [a11y-coverage.ru.md](./a11y-coverage.ru.md).\n\n${n} criteria (WCAG 2.2 removed 4.1.1 Parsing). **Coverage** says what the tools can do on their own: *automated* — every piece of evidence the criterion asks for has an automated option; *partly* — some of it; *manual* — only a person can verify it. **Fails on** lists the scripts whose findings turn the cell red even where a review is still needed. Counts are components (patterns in brackets). Browser checks last run: ${date}.`,
    head: '| Criterion | Level | Checked by | Fails on | Coverage | Verified | Partly | Untested | Fails | n/a |',
    scope: { product: 'the product (its pages, content and media)', library: 'the product, with library support (layouts, orientation)' },
    cov: { automated: 'automated', partly: 'partly', manual: 'manual' },
    either: ' or ',
    summary: (a, p, m, o) => `**Summary:** ${a} automated, ${p} partly, ${m} manual, ${o} outside the components (product or library level).`,
  },
  ru: {
    title: 'Покрытие доступности: WCAG 2.2 A/AA',
    intro: (n, date) =>
      `Генерируется \`scripts/build-a11y-coverage.mjs\` из \`spec/a11y.json\` (матрица доступности). Не править руками. English: [a11y-coverage.md](./a11y-coverage.md).\n\n${n} критериев (в WCAG 2.2 нет 4.1.1 Parsing). **Покрытие** — что инструменты могут сами: *автоматически* — для каждого вида доказательства, которого требует критерий, есть автоматический вариант; *частично* — для части; *вручную* — проверить может только человек. **Падает на** — скрипты, чьи находки делают ячейку красной, даже если нужна ещё ручная проверка. Числа — компоненты (паттерны в скобках). Последний прогон браузерных проверок: ${date}.`,
    head: '| Критерий | Уровень | Чем проверяется | Падает на | Покрытие | Проверено | Частично | Не проверено | Нарушено | n/a |',
    scope: { product: 'продукт (его страницы, контент и медиа)', library: 'продукт с опорой на библиотеку (раскладки, ориентация)' },
    cov: { automated: 'автоматически', partly: 'частично', manual: 'вручную' },
    either: ' или ',
    summary: (a, p, m, o) => `**Итого:** ${a} автоматически, ${p} частично, ${m} вручную, ${o} вне компонентов (уровень продукта или библиотеки).`,
  },
};

function coverage(c) {
  if (c.scope !== 'component') return c.scope;
  const groups = (c.evidence ?? []).map((e) => e.split('|'));
  if (!groups.length) return 'manual';
  const autoGroups = groups.filter((g) => g.some((k) => TOOL[k]?.auto)).length;
  return autoGroups === groups.length ? 'automated' : autoGroups ? 'partly' : 'manual';
}

function render(lang) {
  const t = T[lang];
  const n = (counts, pcounts, k) => `${counts?.[k] ?? 0}${pcounts?.[k] ? ` (${pcounts[k]})` : ''}`;
  const tally = { automated: 0, partly: 0, manual: 0, other: 0 };
  const lines = matrix.criteria.map((c) => {
    const cov = coverage(c);
    if (cov in tally) tally[cov]++;
    else tally.other++;
    if (c.scope !== 'component') return `| ${c.id} ${c.name} | ${c.level} | ${t.scope[c.scope] ?? c.scope} | — | — | — | — | — | — | — |`;
    const tools = (c.evidence ?? []).map((e) => e.split('|').map((k) => TOOL[k]?.[lang] ?? k).join(t.either)).join(' + ');
    return `| ${c.id} ${c.name} | ${c.level} | ${tools || '—'} | ${(c.gates ?? []).join(', ') || '—'} | ${t.cov[cov]} | ${n(c.counts, c.patternCounts, 'verified')} | ${n(c.counts, c.patternCounts, 'partial')} | ${n(c.counts, c.patternCounts, 'untested')} | ${n(c.counts, c.patternCounts, 'fails')} | ${n(c.counts, c.patternCounts, 'n/a')} |`;
  });
  return `# ${t.title}\n\n${t.intro(matrix.criteria.length, matrix.autoChecked ?? '—')}\n\n${t.head}\n|---|---|---|---|---|---|---|---|---|---|\n${lines.join('\n')}\n\n${t.summary(tally.automated, tally.partly, tally.manual, tally.other)}\n`;
}

let stale = false;
for (const [lang, file] of [['en', 'docs/a11y-coverage.md'], ['ru', 'docs/a11y-coverage.ru.md']]) {
  const out = render(lang);
  const target = path.join(REPO, file);
  if (CHECK) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== out) {
      console.error(`${file} is stale — run \`node scripts/build-a11y-coverage.mjs\``);
      stale = true;
    }
  } else fs.writeFileSync(target, out);
}
if (stale) process.exit(1);
console.log(`a11y coverage: ${matrix.criteria.length} criteria → docs/a11y-coverage(.ru).md${CHECK ? ' (checked)' : ''}`);
