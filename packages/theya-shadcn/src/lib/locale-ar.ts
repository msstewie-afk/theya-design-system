const rules = new Intl.PluralRules('ar');
/** Arabic plural forms: zero, one, two, few (3–10), many (11–99), other. */
const plural = (n: number, forms: { one: string; two: string; few: string; many: string }) => {
  const form = rules.select(n);
  if (form === 'one') return forms.one;
  if (form === 'two') return forms.two;
  if (form === 'few') return `${n} ${forms.few}`;
  return `${n} ${forms.many}`;
};

