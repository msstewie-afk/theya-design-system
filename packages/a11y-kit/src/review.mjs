/**
 * The change review: an agent reads one change (a commit range or a pull
 * request) against WCAG 2.2 A/AA and reports what the deterministic checks
 * can't see. Its findings are an opinion: they open issues for a person,
 * never fail a build, and are scored afterwards (precision).
 *
 * Pieces, all deterministic except the agent itself:
 * - renderContext(): what the agent is given besides the diff — which
 *   criteria the scripts already prove (skip them), which they cover only in
 *   part (and with what), which are manual, the design system's accepted
 *   deviations and documents to read.
 * - checkFindings(): the agent's findings.json against the schema and the
 *   pre-flight rules; a finding that fails them is dropped or downgraded,
 *   with the reason kept in the report.
 * - renderComment(): the one comment posted on the change.
 * - fingerprint(): so the same finding on a later change doesn't open a
 *   second issue.
 */
import crypto from 'node:crypto';

export const KINDS = {
  violation: 'Violation',
  decision: 'Needs a design decision',
  run: 'Needs a run',
};

/** The agent's context: registry coverage minus what scripts prove, plus the design system's own notes. */
export function renderContext({ reg, notes = '', read = [], tokens }) {
  const byId = new Map(reg.checks.map((c) => [c.id, c]));
  const crit = reg.coverage.filter((c) => c.where !== 'product');
  const proven = crit.filter((c) => c.automation === 'automated');
  const rest = crit.filter((c) => c.automation !== 'automated');
  const product = reg.coverage.filter((c) => c.where === 'product');
  const line = (id) => {
    const c = byId.get(id);
    return c ? `  - \`${id}\` (${c.depth}${c.id.startsWith('axe.') ? '' : `, ${c.tool}`}): ${c.how}` : `  - \`${id}\``;
  };
  const out = [
    '# Review context',
    '',
    `Generated by \`a11y-kit review-context\` from the check registry (axe-core ${reg.axeVersion}). Do not edit.`,
    '',
    '## Proven by scripts — do not review',
    '',
    'Every change runs these checks in CI; a clean run verifies the criterion for what the stories render. Report against them only if the change removes or weakens a story that exercises them (then: kind "run").',
    '',
    proven.map((c) => `- ${c.id} ${c.name} (${c.level})`).join('\n'),
    '',
    '## Partly covered or manual — this is what you review',
    '',
    'For each: what the scripts already see, so you look at the rest. A depth of "full" means that side is settled; "part", "gate" and "advisory" leave the criterion open.',
    '',
    ...rest.map((c) =>
      [
        `### ${c.id} ${c.name} (${c.level}, ${c.automation})`,
        '',
        c.checks.filter((x) => !x.startsWith('manual.')).length
          ? `Scripts:\n${c.checks.filter((x) => !x.startsWith('manual.')).map(line).join('\n')}`
          : 'Scripts: none.',
        '',
      ].join('\n'),
    ),
    '## Product-level — out of scope for a design-system change',
    '',
    product.map((c) => `${c.id}`).join(', '),
    '',
  ];
  if (tokens)
    out.push(
      '## Recomputing contrast',
      '',
      'Never state a contrast ratio you did not compute. From the repository root:',
      '',
      '```',
      tokens.command,
      '```',
      '',
      `Arguments are colours or token names (with or without \`--\`) from this design system's CSS (${tokens.files.join(', ')}); translucent colours are composited over --base (default: ${tokens.page}). Thresholds: text 4.5:1 (3:1 at 24px, or 18.66px bold, and up), non-text 3:1.`,
      '',
    );
  if (notes) out.push('## This design system: accepted deviations and rules', '', notes.trim(), '');
  if (read.length) out.push('## Read before reviewing', '', read.map((f) => `- \`${f}\``).join('\n'), '');
  return out.join('\n');
}

const LEVELS = new Set(['A', 'AA']);

/**
 * Validates the agent's findings. Returns { kept, dropped } where every
 * dropped entry carries `why`. Rules:
 * - shape: kind, sc, level, title, evidence, file required;
 * - level must be A or AA and match the registry's level for sc (AAA is out of scope);
 * - sc must be a WCAG 2.2 criterion the registry knows and not product-level;
 * - a violation must say it was checked against the code (precheck.code = true)
 *   and, for contrast criteria, carry a recomputed ratio; otherwise it is
 *   downgraded to "run";
 * - a criterion the scripts prove in full is dropped unless kind is "run".
 */
export function checkFindings(data, reg) {
  const crit = new Map(reg.coverage.map((c) => [c.id, c]));
  const kept = [];
  const dropped = [];
  for (const f of Array.isArray(data?.findings) ? data.findings : []) {
    const miss = ['kind', 'sc', 'level', 'title', 'evidence', 'file'].filter((k) => !f[k]);
    if (miss.length) {
      dropped.push({ ...f, why: `missing ${miss.join(', ')}` });
      continue;
    }
    if (!KINDS[f.kind]) {
      dropped.push({ ...f, why: `unknown kind "${f.kind}"` });
      continue;
    }
    const c = crit.get(f.sc);
    if (!c) {
      dropped.push({ ...f, why: `${f.sc} is not a WCAG 2.2 A/AA criterion` });
      continue;
    }
    if (!LEVELS.has(f.level) || f.level !== c.level) {
      dropped.push({ ...f, why: `level ${f.level} does not match ${f.sc} (${c.level})` });
      continue;
    }
    if (c.where === 'product') {
      dropped.push({ ...f, why: `${f.sc} is judged on the product, not the design system` });
      continue;
    }
    if (c.automation === 'automated' && f.kind !== 'run') {
      dropped.push({ ...f, why: `${f.sc} is proven by scripts in CI` });
      continue;
    }
    const g = { ...f, precheck: f.precheck ?? {} };
    if (g.kind === 'violation') {
      const contrastSc = ['1.4.3', '1.4.11', '2.4.7', '2.4.11'].includes(g.sc) && /contrast|ratio|:1/i.test(`${g.title} ${g.evidence}`);
      if (g.precheck.code !== true) g.downgraded = 'not checked against the code';
      else if (contrastSc && !/^\d+(\.\d+)?:1$/.test(String(g.precheck.recomputed ?? ''))) g.downgraded = 'contrast not recomputed with `a11y-kit contrast`';
      if (g.downgraded) g.kind = 'run';
    }
    kept.push(g);
  }
  return { kept, dropped };
}

export const fingerprint = (f) =>
  crypto
    .createHash('sha1')
    .update([f.sc, f.component ?? '', f.file, f.title.toLowerCase().replace(/\s+/g, ' ').trim()].join('|'))
    .digest('hex')
    .slice(0, 12);

/** The comment on the change. `issues` maps fingerprint → issue number (opened or already open). */
export function renderComment({ change, kept, dropped, issues = {}, summary = '', run }) {
  const head = `### Accessibility review — ${change}`;
  if (!kept.length && !dropped.length)
    return `${head}\n\nNothing to report against WCAG 2.2 A/AA beyond what the CI checks prove.${summary ? `\n\n${summary}` : ''}\n\n<sub>An opinion, not a verdict: it opens issues for a person and never fails a build.${run ? ` [Run](${run})` : ''}</sub>`;
  const out = [head, ''];
  if (summary) out.push(summary, '');
  for (const kind of Object.keys(KINDS)) {
    const list = kept.filter((f) => f.kind === kind);
    if (!list.length) continue;
    out.push(`**${KINDS[kind]}** (${list.length})`, '');
    for (const f of list) {
      const fp = fingerprint(f);
      const where = `\`${f.file}${f.line ? `:${f.line}` : ''}\``;
      const issue = issues[fp] ? ` — #${issues[fp]}` : '';
      out.push(`- **${f.sc} ${f.level}** ${f.title} (${where})${issue}`);
      out.push(`  ${f.evidence.replace(/\n+/g, ' ')}`);
      if (f.kind === 'run' && f.check) out.push(`  Run: \`${f.check}\``);
      if (f.downgraded) out.push(`  _Reported as a violation; downgraded: ${f.downgraded}._`);
    }
    out.push('');
  }
  if (dropped.length) {
    out.push('<details><summary>Dropped by the pre-flight check (' + dropped.length + ')</summary>', '');
    for (const f of dropped) out.push(`- ${f.sc ?? '?'} ${f.title ?? '(untitled)'} — ${f.why}`);
    out.push('', '</details>', '');
  }
  out.push(`<sub>An opinion, not a verdict: it opens issues for a person and never fails a build. Close an issue as completed if the finding was right, as not planned if it was wrong — \`a11y-kit review-precision\` counts them.${run ? ` [Run](${run})` : ''}</sub>`);
  return out.join('\n');
}

export function issueBody(f, change) {
  return [
    `**${f.sc} ${f.level}** · ${KINDS[f.kind]}${f.component ? ` · ${f.component}` : ''}`,
    '',
    `File: \`${f.file}${f.line ? `:${f.line}` : ''}\` · Change: ${change}`,
    '',
    f.evidence,
    '',
    f.precheck && Object.keys(f.precheck).length ? `Pre-flight: ${Object.entries(f.precheck).map(([k, v]) => `${k}: ${v}`).join(' · ')}` : '',
    f.kind === 'run' && f.check ? `Run: \`${f.check}\`` : '',
    '',
    'Close as **completed** if this was right (fixed or confirmed), **not planned** if it was wrong.',
    '',
    `<!-- a11y-review:${fingerprint(f)} -->`,
  ]
    .filter((l, i, a) => l !== '' || a[i - 1] !== '')
    .join('\n');
}

/** Precision from closed review issues: completed = right, not planned = wrong. */
export function precision(issues) {
  const closed = issues.filter((i) => i.state === 'closed');
  const right = closed.filter((i) => i.state_reason === 'completed').length;
  const wrong = closed.filter((i) => i.state_reason === 'not_planned').length;
  const byKind = {};
  for (const i of issues) {
    const kind = i.labels.map((l) => l.name ?? l).find((n) => n.startsWith('a11y-review:'))?.slice(12) ?? 'unknown';
    const k = (byKind[kind] ??= { open: 0, right: 0, wrong: 0 });
    if (i.state === 'open') k.open++;
    else if (i.state_reason === 'completed') k.right++;
    else if (i.state_reason === 'not_planned') k.wrong++;
  }
  return { total: issues.length, open: issues.length - closed.length, right, wrong, precision: right + wrong ? right / (right + wrong) : null, byKind };
}
