/** The registry as a list a person reads: every check, then every criterion with what covers it. EN and RU. */
const T = {
  en: {
    title: 'Accessibility checks',
    intro: (n, axe) =>
      `Generated by \`a11y-kit registry\` from the kit's registry and the rule metadata of axe-core ${axe}. Do not edit. ${n} checks.\n\n**Stage**: code (source, no browser), component (a built Storybook), page (a product's URLs), manual (a person), pr (the review agent: an opinion, never fails a build). **Depth**: full — a clean result verifies the criterion for what is rendered; part — one side of it; gate — a finding fails the cell, a clean result proves nothing alone; advisory — listed for a person, never failing. **Runs**: for axe rules, whether the rule runs without being switched on by name. **Calibration**: what the check is proven on (axe: the per-rule calibration; the kit's own checks: the calibration stories it must catch and pass). "—" means not proven yet.`,
    checks: '## Checks',
    head: '| Check | Criteria | Stage | Depth | Runs | Calibration | Where | How it works |',
    cov: '## Criteria',
    covHead: '| Criterion | Level | Where | Automation | Calibrated checks | Not yet calibrated | Manual |',
    auto: { automated: 'automated', partly: 'partly', manual: 'manual' },
    problems: '## Registry problems',
  },
  ru: {
    title: 'Проверки доступности',
    intro: (n, axe) =>
      `Генерируется \`a11y-kit registry\` из реестра набора и метаданных правил axe-core ${axe}. Не править руками. Проверок: ${n}.\n\n**Стадия**: code (код, без браузера), component (собранный Storybook), page (страницы продукта), manual (человек), pr (агент-ревьюер: мнение, сборку не роняет). **Глубина**: full — чистый результат подтверждает критерий для того, что отрисовано; part — одну его сторону; gate — находка делает ячейку красной, чистый результат сам ничего не доказывает; advisory — подсказка человеку, никогда не роняет. **Запуск**: для правил axe — запускается ли правило без явного включения по имени. **Калибровка**: на чём проверка доказана (axe: калибровка по правилу; свои проверки: калибровочные сториз, которые она должна поймать и пропустить). «—» — ещё не доказано.`,
    checks: '## Проверки',
    head: '| Проверка | Критерии | Стадия | Глубина | Запуск | Калибровка | Где | Как работает |',
    cov: '## Критерии',
    covHead: '| Критерий | Уровень | Где | Автоматизация | Откалиброванные проверки | Ещё не откалиброваны | Человек |',
    auto: { automated: 'автоматически', partly: 'частично', manual: 'вручную' },
    problems: '## Ошибки реестра',
  },
};
const cell = (s) => String(s ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderList(reg, lang) {
  const t = T[lang];
  const cal = (c) => {
    if (c.id.startsWith('axe.')) return c.calibration ? `${c.calibration.result}${c.calibration.note ? `: ${c.calibration.note}` : ''}` : '—';
    return c.calibration.length ? c.calibration.join('; ') : '—';
  };
  const rows = [...reg.checks]
    .sort((a, b) => a.sc[0].localeCompare(b.sc[0], 'en', { numeric: true }) || a.id.localeCompare(b.id))
    .map((c) => `| \`${c.id}\` | ${c.sc.join(', ')} | ${c.stage} | ${c.depth} | ${c.runs ?? '—'} | ${cell(cal(c))} | ${c.where} | ${cell(c.how)} |`);
  const cov = reg.coverage.map(
    (c) =>
      `| ${c.id} ${c.name} | ${c.level} | ${c.where} | ${t.auto[c.automation]} | ${c.calibrated.map((x) => `\`${x}\``).join(', ') || '—'} | ${c.uncalibrated.map((x) => `\`${x}\``).join(', ') || '—'} | ${c.checks.filter((x) => x.startsWith('manual.')).join(', ') || '—'} |`,
  );
  const problems = reg.problems.length ? `\n${t.problems}\n\n${reg.problems.map((p) => `- ${p}`).join('\n')}\n` : '';
  return `# ${t.title}\n\n${t.intro(reg.checks.length, reg.axeVersion)}\n\n${t.checks}\n\n${t.head}\n|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n\n${t.cov}\n\n${t.covHead}\n|---|---|---|---|---|---|---|\n${cov.join('\n')}\n${problems}`;
}

export function renderCompare(cmp) {
  const lines = [];
  lines.push(`# Checklist against the registry\n`);
  lines.push(`${cmp.rows.length} rows, ${cmp.rows.length - cmp.unmatched.length} matched.\n`);
  const sec = (title, items, fmt) => items.length && lines.push(`## ${title} (${items.length})\n\n${items.map(fmt).join('\n')}\n`);
  sec('Not an axe rule or a registry check (criterion-level rows: what the registry has for the criterion)', cmp.unmatched, (r) => `- \`${r.id}\` (${r.sc.join(', ') || 'no criterion'}) → ${r.cover.filter((c) => !c.startsWith('axe.')).map((c) => `\`${c}\``).join(', ') || 'nothing'}`);
  sec("axe rules that don't run unless switched on by name", cmp.notDefault, (r) => `- \`${r.id}\` → ${r.runs}`);
  sec('Criteria the row leaves out (axe maps the rule to more)', cmp.lostSc, (r) => `- \`${r.id}\`: also ${r.missingSc.join(', ')}`);
  sec('WCAG 2.2 A/AA criteria with no row', cmp.criteriaMissing, (c) => `- ${c}`);
  sec('Registry checks the list has no row for', cmp.registryOnly, (c) => `- \`${c}\``);
  return lines.join('\n');
}
